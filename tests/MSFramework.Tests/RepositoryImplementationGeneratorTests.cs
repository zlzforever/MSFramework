using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Xunit;

namespace MSFramework.Tests;

/// <summary>
/// EF 仓储实现源生成器测试（<see cref="MicroserviceFramework.Ef.Analyzers.RepositoryGenerator"/>）：
/// 验证命名空间段映射（Domain→Infrastructure、AggregateRoots/Aggregates→Repositories）、
/// 键/无键仓储基类型、全局命名空间的 MSF0001 诊断与非聚合根类型跳过
/// </summary>
public class RepositoryImplementationGeneratorTests
{
    /// <summary>
    /// 构建 Domain 编译单元（程序集名 Test.Domain），引用运行时与 MSFramework 主程序集，
    /// 使聚合根接口（IAggregateRoot）可被语义模型解析
    /// </summary>
    /// <param name="source">Domain 层 C# 源码</param>
    /// <returns>Domain 编译单元</returns>
    private static CSharpCompilation CreateDomainCompilation(string source)
    {
        var references = new List<MetadataReference>
        {
            MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
            MetadataReference.CreateFromFile(
                typeof(MicroserviceFramework.Domain.IAggregateRoot<>).Assembly.Location)
        };

        return CSharpCompilation.Create("Test.Domain",
            [CSharpSyntaxTree.ParseText(source)],
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    }

    /// <summary>
    /// 构建 Infrastructure 编译单元（程序集名 Test.Infrastructure，经程序集名段映射
    /// Domain→Infrastructure 反推引用 Test.Domain 的<b>源</b>编译单元）并运行生成器
    /// </summary>
    /// <param name="infrastructureSource">Infrastructure 层 C# 源码</param>
    /// <param name="domainCompilation">Domain 编译单元（必须经 ToMetadataReference 引用，
    /// 生成器依赖 <c>ReferencedAssemblySymbols</c> 拿到源符号而非 PE 元数据）</param>
    /// <returns>生成器运行结果</returns>
    private static GeneratorDriverRunResult RunGenerator(string infrastructureSource,
        CSharpCompilation domainCompilation)
    {
        var infrastructure = CSharpCompilation.Create("Test.Infrastructure",
            [CSharpSyntaxTree.ParseText(infrastructureSource)],
            [
                MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
                MetadataReference.CreateFromFile(
                    typeof(MicroserviceFramework.Domain.IAggregateRoot<>).Assembly.Location),
                domainCompilation.ToMetadataReference()
            ],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var driver = CSharpGeneratorDriver.Create(
            new MicroserviceFramework.Ef.Analyzers.RepositoryGenerator());
        return driver.RunGenerators(infrastructure).GetRunResult();
    }

    /// <summary>
    /// 实现泛型 IAggregateRoot&lt;TKey&gt; 的聚合根：生成带键仓储实现，
    /// 命名空间段按约定映射（Domain→Infrastructure、AggregateRoots→Repositories）
    /// </summary>
    [Fact]
    public void AggregateRootWithKey_GeneratesKeyedRepositoryImplementation()
    {
        var domain = CreateDomainCompilation("""
                                             using MicroserviceFramework.Domain;

                                             namespace Test.Domain.AggregateRoots;

                                             public class Product : IAggregateRoot<int>
                                             {
                                                 public int Id { get; }
                                                 public Product(int id) { Id = id; }
                                             }
                                             """);

        var result = RunGenerator("namespace Test.Infrastructure;", domain);

        var tree = Assert.Single(result.GeneratedTrees);
        Assert.EndsWith("Test.Domain.Repositories.Product.g.cs", tree.FilePath);
        var text = tree.GetText().ToString();
        Assert.Contains("namespace Test.Infrastructure.Repositories;", text);
        // E 别名指向聚合根类型的完整显示名（using 段中的 Repositories 为无害的未使用 using）
        Assert.Contains("using E = Test.Domain.AggregateRoots.Product;", text);
        Assert.Contains("public partial class ProductRepository", text);
        Assert.Contains("EfRepository<E, int>", text);
        Assert.Contains("IProductRepository", text);
        // 顶层声明顶格，类成员及构造器括号保持四空格缩进。
        Assert.Equal(new[]
        {
            "// <auto-generated />",
            "using MicroserviceFramework.Ef;",
            "using MicroserviceFramework.Ef.Repositories;",
            "using Test.Domain.Repositories;",
            "using E = Test.Domain.AggregateRoots.Product;",
            "",
            "namespace Test.Infrastructure.Repositories;",
            "",
            "/// <summary>聚合根 <see cref=\"E\"/> 的 EF 仓储实现，依赖当前作用域上下文工厂。</summary>",
            "public partial class ProductRepository",
            "    : EfRepository<E, int>, IProductRepository",
            "{",
            "    /// <summary>使用实体所属的作用域上下文创建仓储。</summary>",
            "    /// <param name=\"context\">框架上下文工厂，须已注册实体映射。</param>",
            "    public ProductRepository(DbContextFactory context) : base(context)",
            "    {",
            "    }",
            "}"
        }, text.Replace("\r\n", "\n").Split('\n'));
    }

    /// <summary>
    /// 实现非泛型 IAggregateRoot 的聚合根（复合主键多属性实体）：生成无键仓储 EfRepository&lt;E&gt;
    /// </summary>
    [Fact]
    public void KeylessAggregateRoot_GeneratesKeylessRepositoryImplementation()
    {
        var domain = CreateDomainCompilation("""
                                             using MicroserviceFramework.Domain;

                                             namespace Test.Domain.Aggregates;

                                             public class Product : IAggregateRoot
                                             {
                                             }
                                             """);

        var result = RunGenerator("namespace Test.Infrastructure;", domain);

        var tree = Assert.Single(result.GeneratedTrees);
        var text = tree.GetText().ToString();
        Assert.Contains("namespace Test.Infrastructure.Repositories;", text);
        Assert.Contains("public partial class ProductRepository", text);
        Assert.Contains(": EfRepository<E>, IProductRepository", text);
        // 无键仓储不应带主键类型参数
        Assert.DoesNotContain("EfRepository<E, ", text);
    }

    /// <summary>
    /// 全局命名空间聚合根：生成 MSF0001 编译错误（含类型名与 Domain 源位置）且不生成仓储实现
    /// </summary>
    [Fact]
    public void GlobalNamespaceAggregateRoot_ReportsMsf0001ErrorAndSkipsGeneration()
    {
        var domain = CreateDomainCompilation("""
                                             using MicroserviceFramework.Domain;

                                             public class GlobalAggregate : IAggregateRoot<int>
                                             {
                                                 public int Id { get; }
                                                 public GlobalAggregate(int id) { Id = id; }
                                             }
                                             """);

        var result = RunGenerator("namespace Test.Infrastructure;", domain);

        var diagnostic = Assert.Single(
            result.Diagnostics.Where(x => x.Id == "MSF0001"));
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
        Assert.Contains("GlobalAggregate", diagnostic.GetMessage());
        // 诊断定位到 Domain 源中类型声明行（源码第 3 行，0 起始为 2）
        Assert.Equal(2, diagnostic.Location.GetLineSpan().StartLinePosition.Line);

        // 不生成该聚合根的仓储实现
        Assert.DoesNotContain(result.GeneratedTrees,
            tree => tree.FilePath.Contains("GlobalAggregate", StringComparison.Ordinal));
    }

    /// <summary>
    /// Domain 中未实现 IAggregateRoot 的普通类：不生成任何仓储实现，也无诊断
    /// </summary>
    [Fact]
    public void NonAggregateRoot_GeneratesNothing()
    {
        var domain = CreateDomainCompilation("""
                                             namespace Test.Domain.AggregateRoots;

                                             public class NotAnAggregate
                                             {
                                                 public int Id { get; }
                                             }
                                             """);

        var result = RunGenerator("namespace Test.Infrastructure;", domain);

        Assert.Empty(result.GeneratedTrees);
        Assert.Empty(result.Diagnostics);
    }

    /// <summary>
    /// 关键字命名的聚合根（@event）：生成仓储实现——旧实现收集"转义显示名"再按元数据名回查
    /// 会被 <see cref="Compilation.GetTypeByMetadataName"/> 拒收，导致该类型静默漏生成实现
    /// （而接口生成器正常生成，成对失配）
    /// </summary>
    [Fact]
    public void KeywordNamedAggregateRoot_GeneratesRepositoryImplementation()
    {
        var domain = CreateDomainCompilation("""
                                             using MicroserviceFramework.Domain;

                                             namespace Test.Domain.AggregateRoots;

                                             public class @event : IAggregateRoot<int>
                                             {
                                                 public int Id { get; }
                                                 public @event(int id) { Id = id; }
                                             }
                                             """);

        var result = RunGenerator("namespace Test.Infrastructure;", domain);

        Assert.Empty(result.Diagnostics);
        var tree = Assert.Single(result.GeneratedTrees);
        var text = tree.GetText().ToString();
        // 别名按转义显示名生成
        Assert.Contains("using E = Test.Domain.AggregateRoots.@event;", text);
        Assert.Contains("public partial class eventRepository", text);
        Assert.Contains("IeventRepository", text);
    }

    /// <summary>
    /// Domain 程序集不含任何聚合根：生成结果为空
    /// </summary>
    [Fact]
    public void DomainWithoutAggregateRoots_GeneratesNothing()
    {
        var domain = CreateDomainCompilation("""
                                             namespace Test.Domain;

                                             public class PlainService
                                             {
                                             }
                                             """);

        var result = RunGenerator("namespace Test.Infrastructure;", domain);

        Assert.Empty(result.GeneratedTrees);
        Assert.Empty(result.Diagnostics);
    }

    /// <summary>
    /// 聚合根未放在约定命名空间段：报 MSF0002 警告且不生成孤儿仓储实现
    /// （与接口生成器成对一致：接口未生成 → 实现也不生成，否则编译失败）
    /// </summary>
    [Fact]
    public void MissingAggregateSegment_ReportsMsf0002WarningAndSkipsImplementation()
    {
        var domain = CreateDomainCompilation("""
                                             using MicroserviceFramework.Domain;

                                             namespace Test.Domain.Models;

                                             public class Product : IAggregateRoot<int>
                                             {
                                                 public int Id { get; }
                                                 public Product(int id) { Id = id; }
                                             }
                                             """);

        var result = RunGenerator("namespace Test.Infrastructure;", domain);

        var diagnostic = Assert.Single(
            result.Diagnostics.Where(x => x.Id == "MSF0002"));
        Assert.Equal(DiagnosticSeverity.Warning, diagnostic.Severity);
        Assert.Contains("Test.Domain.Models", diagnostic.GetMessage());
        Assert.Empty(result.GeneratedTrees);
    }
}
